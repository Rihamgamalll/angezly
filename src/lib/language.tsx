  localStorage.setItem('dawrak-language',language);
  document.documentElement.lang=language; document.documentElement.dir=language==='ar'?'rtl':'ltr';
  let pending=false;
  const refresh=()=>{if(pending)return;pending=true;requestAnimationFrame(()=>{pending=false;translateDom(document.body);});};
  refresh();
