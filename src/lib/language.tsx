export const translate = (text:string) => {
  if (translations[text]) return translations[text];
  // Preserve variable values in dynamic labels such as "3 أماكن متاحة".
  const match = text.match(/^([\d٠-٩۰-۹]+)\s+(.+)$/);
  if (match && translations[match[2]]) return `${match[1]} ${translations[match[2]]}`;
  return text;
};
function translateDom(root: ParentNode) {
 const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
 let node: Node | null;
 while ((node = walker.nextNode())) {
  const parent = node.parentElement;
  if (!parent || ['SCRIPT','STYLE','TEXTAREA','INPUT','OPTION'].includes(parent.tagName) || parent.isContentEditable || parent.closest('[data-no-translate]')) continue;
  const raw = node.textContent || ''; const trimmed = raw.trim();
  if (!trimmed) continue;
  const tracked = node as Node & {__originalAr?:string};
  const previous = tracked.__originalAr;
  const original = previous && (trimmed === previous || trimmed === translate(previous)) ? previous : trimmed;
  tracked.__originalAr = original;
  const translated = document.documentElement.lang === 'en' ? translate(original) : original;
  if (trimmed !== translated) node.textContent = raw.replace(trimmed, translated);
 }
 root.querySelectorAll?.('[placeholder],[aria-label],[title]').forEach(el => {
  for (const attr of ['placeholder','aria-label','title']) {
   const current = el.getAttribute(attr); if (!current) continue;
   const key = `data-original-${attr}`; const original = el.getAttribute(key) ?? current;
   if (!el.hasAttribute(key)) el.setAttribute(key,original);
   const next = document.documentElement.lang === 'en' ? translate(original) : original;
   if (current !== next) el.setAttribute(attr,next);
  }
 });
}
